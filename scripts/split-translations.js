// Process each locale
['en', 'pl', 'nl'].forEach(locale => {
  const localeDir = path.join(messagesDir, locale);
  if (!fs.existsSync(localeDir)) {
    fs.mkdirSync(localeDir, { recursive: true });
  }

  // Read the main translation file
  const translationPath = path.join(localesDir, locale, 'translation.json');
  if (!fs.existsSync(translationPath)) {
    console.warn(`Translation file not found: ${translationPath}`);
    return;
  }

  const translations = JSON.parse(fs.readFileSync(translationPath, 'utf8'));

  // Split into files
  Object.entries(splitConfig).forEach(([filename, keys]) => {
    const output = {};

    keys.forEach(key => {
      const value = getNestedValue(translations, key);
      if (value !== undefined) {
        setNestedValue(output, key, value);
      }
    });

    // Write the split file
    const outputPath = path.join(localeDir, filename);
    fs.writeFileSync(outputPath, JSON.stringify(output, null, 2), 'utf8');
    console.log(`Created: ${outputPath}`);
  });

  // Copy individual namespace files that already exist
  const namespaces = ['soundDesign', 'middlewareOptimization', 'gradwork'];
  namespaces.forEach(ns => {
    const nsPath = path.join(localesDir, locale, `${ns}.json`);
    if (fs.existsSync(nsPath)) {
      const content = JSON.parse(fs.readFileSync(nsPath, 'utf8'));

      // Determine target filename
      let targetFilename;
      if (ns === 'soundDesign') targetFilename = 'sound-design.json';
      else if (ns === 'middlewareOptimization') targetFilename = 'middleware-optimization.json';
      else targetFilename = `${ns}.json`;

      const outputPath = path.join(localeDir, targetFilename);
      fs.writeFileSync(outputPath, JSON.stringify(content, null, 2), 'utf8');
      console.log(`Copied: ${outputPath}`);
    }
  });
});

console.log('\nTranslation files split successfully!');
